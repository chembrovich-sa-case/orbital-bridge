import os
import subprocess
import datetime
from pathlib import Path
from src.config import PROJECTS_DIR


def list_projects() -> list[dict]:
    """List existing projects in PROJECTS_DIR."""
    if not PROJECTS_DIR.exists():
        return []

    projects = []
    for item in PROJECTS_DIR.iterdir():
        if item.is_dir() and not item.name.startswith("."):
            try:
                mtime = item.stat().st_mtime
                mod_date = datetime.datetime.fromtimestamp(mtime).strftime("%d.%m %H:%M")
                has_git = (item / ".git").exists()
                projects.append({
                    "name": item.name,
                    "path": str(item),
                    "modified": mod_date,
                    "git": has_git,
                })
            except Exception:
                continue

    projects.sort(key=lambda x: x["name"].lower())
    return projects


def scaffold_project(name: str, template: str = "python") -> dict:
    """
    Create a new project folder with starter files and git init.
    Supported templates: python, fastapi, web, empty.
    """
    safe_name = "".join(c for c in name if c.isalnum() or c in ("-", "_")).strip()
    if not safe_name:
        return {"success": False, "error": "Некорректное имя проекта"}

    target_dir = PROJECTS_DIR / safe_name
    if target_dir.exists():
        return {"success": False, "error": f"Папка {safe_name} уже существует!"}

    target_dir.mkdir(parents=True, exist_ok=True)

    template = template.lower()
    created_files = []

    # Common .gitignore
    gitignore_content = """# Python
__pycache__/
*.py[cod]
.venv/
env/
.env

# Node
node_modules/
dist/
.DS_Store

# IDE
.idea/
.vscode/
"""
    (target_dir / ".gitignore").write_text(gitignore_content, encoding="utf-8")
    created_files.append(".gitignore")

    # Common README
    readme_content = f"""# {safe_name}

Auto-generated by Orbital Bridge at {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}.

## Template
`{template}`

## Getting Started
"""

    if template == "fastapi":
        main_py = '''from fastapi import FastAPI

app = FastAPI(title="''' + safe_name + '''", version="1.0.0")

@app.get("/")
def read_root():
    return {"status": "ok", "project": "''' + safe_name + '''"}

@app.get("/health")
def health():
    return {"alive": True}

if __name__ == "__main__":
    import uvicorn
    uvicorn.run("main:app", host="127.0.0.1", port=8000, reload=True)
'''
        reqs = "fastapi>=0.115.0\nuvicorn[standard]>=0.30.0\npydantic>=2.0\n"
        (target_dir / "main.py").write_text(main_py, encoding="utf-8")
        (target_dir / "requirements.txt").write_text(reqs, encoding="utf-8")
        readme_content += "Run `pip install -r requirements.txt` then `python main.py`\n"
        created_files.extend(["main.py", "requirements.txt"])

    elif template == "web":
        html = f"""<!DOCTYPE html>
<html lang="ru">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{safe_name}</title>
  <style>
    body {{
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
      background: #0d1117;
      color: #c9d1d9;
      display: flex;
      flex-direction: column;
      align-items: center;
      justify-content: center;
      min-height: 100vh;
      margin: 0;
    }}
    .card {{
      background: #161b22;
      border: 1px solid #30363d;
      border-radius: 12px;
      padding: 32px;
      text-align: center;
    }}
    h1 {{ color: #58a6ff; margin-bottom: 8px; }}
  </style>
</head>
<body>
  <div class="card">
    <h1>🚀 {safe_name}</h1>
    <p>Project initialized via Orbital Bridge</p>
  </div>
</body>
</html>
"""
        (target_dir / "index.html").write_text(html, encoding="utf-8")
        readme_content += "Open `index.html` in your browser.\n"
        created_files.append("index.html")

    elif template == "python":
        main_py = f'''"""
{safe_name} - Main entry point
"""

def main():
    print("🚀 Hello from {safe_name}!")

if __name__ == "__main__":
    main()
'''
        reqs = "# Add project dependencies here\n"
        (target_dir / "main.py").write_text(main_py, encoding="utf-8")
        (target_dir / "requirements.txt").write_text(reqs, encoding="utf-8")
        readme_content += "Run `python main.py`.\n"
        created_files.extend(["main.py", "requirements.txt"])

    (target_dir / "README.md").write_text(readme_content, encoding="utf-8")
    created_files.append("README.md")

    # Run git init
    git_initialized = False
    try:
        subprocess.run(["git", "init"], cwd=str(target_dir), capture_output=True, check=True)
        subprocess.run(["git", "add", "."], cwd=str(target_dir), capture_output=True, check=True)
        subprocess.run(
            ["git", "commit", "-m", "Initial commit from Orbital Bridge"],
            cwd=str(target_dir),
            capture_output=True,
            check=True,
        )
        git_initialized = True
    except Exception:
        git_initialized = False

    return {
        "success": True,
        "name": safe_name,
        "path": str(target_dir),
        "template": template,
        "files": created_files,
        "git": git_initialized,
    }
